"""Emit the reviewer-response table (LaTeX + Markdown) from training_metadata.json.

Generated, never hand-transcribed, so the manuscript numbers cannot drift from
what the artifacts actually say.

Usage:  ./flowsync/bin/python acm_tomm_metadata/make_table.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# Downlink first, then uplink; ascending test MAE within each group.
ORDER = ['Kombat_DL', 'Forza_DL', 'Fortnite_DL',
         'Fortnite_UL', 'Forza_UL', 'Kombat_UL']

PRETTY = {
    'Kombat_DL': 'Mortal Kombat (DL)',
    'Forza_DL': 'Forza (DL)',
    'Fortnite_DL': 'Fortnite (DL)',
    'Fortnite_UL': 'Fortnite (UL)',
    'Forza_UL': 'Forza (UL)',
    'Kombat_UL': 'Mortal Kombat (UL)',
}

CAPTION = (
    'Per-model generalization diagnostics for the IPI prediction component. Each '
    'model is trained on 799 non-overlapping windows for a fixed budget of 50 '
    'epochs and evaluated on 199 held-out test windows. MAE is reported on the '
    '$[-1,1]$ min-max scaled IPI series. The increase in error on held-out data '
    'ranges from 3\\% to 82\\% across models, and is largest for the two uplink '
    'models with the sparsest traffic.'
)


def load():
    path = os.path.join(HERE, 'training_metadata.json')
    with open(path) as fh:
        records = json.load(fh)
    by_name = {r['model']: r for r in records}
    return [by_name[n] for n in ORDER if n in by_name]


def latex(rows):
    lines = [
        '% Generated by acm_tomm_metadata/make_table.py -- do not edit by hand.',
        '\\begin{table}[t]',
        '\\centering',
        '\\caption{%s}' % CAPTION,
        '\\label{tab:generalization}',
        '\\setlength{\\tabcolsep}{6pt}',
        '\\begin{tabular}{lrrr}',
        '\\toprule',
        'Trace & Train MAE & Test MAE & Error increase \\\\',
        '\\midrule',
    ]
    for r in rows:
        lines.append('%s & %.4f & %.4f & $+%.0f\\%%$ \\\\' % (
            PRETTY[r['model']], r['train_mae'], r['test_mae'],
            100 * (r['test_over_train_mae'] - 1)))
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    return '\n'.join(lines)


def markdown(rows):
    lines = [
        '| Trace | Train MAE | Held-out test MAE | Error increase on held-out data |',
        '|---|---|---|---|',
    ]
    for r in rows:
        lines.append('| %s | %.4f | %.4f | +%.0f%% |' % (
            PRETTY[r['model']], r['train_mae'], r['test_mae'],
            100 * (r['test_over_train_mae'] - 1)))
    lines.append('')
    return '\n'.join(lines)


def latex_wide(rows):
    """Two-panel variant: downlink and uplink side by side, 3 body rows."""
    by_name = {r['model']: r for r in rows}
    pairs = [('Kombat_DL', 'Kombat_UL'),
             ('Forza_DL', 'Forza_UL'),
             ('Fortnite_DL', 'Fortnite_UL')]
    lines = [
        '% Generated by acm_tomm_metadata/make_table.py -- do not edit by hand.',
        '% Two-panel variant: half the height of table.tex, roughly twice the width.',
        '\\begin{table}[t]',
        '\\centering',
        '\\caption{%s}' % CAPTION,
        '\\label{tab:generalization}',
        '\\setlength{\\tabcolsep}{5pt}',
        '\\begin{tabular}{lrrr@{\\hskip 2em}lrrr}',
        '\\toprule',
        '\\multicolumn{4}{c}{Downlink} & \\multicolumn{4}{c}{Uplink} \\\\',
        '\\cmidrule(lr){1-4} \\cmidrule(lr){5-8}',
        'Trace & Train & Test & Incr. & Trace & Train & Test & Incr. \\\\',
        '\\midrule',
    ]
    for dl, ul in pairs:
        d, u = by_name[dl], by_name[ul]
        game = PRETTY[dl].replace(' (DL)', '')
        lines.append('%s & %.4f & %.4f & $+%.0f\\%%$ & %s & %.4f & %.4f & $+%.0f\\%%$ \\\\' % (
            game, d['train_mae'], d['test_mae'],
            100 * (d['test_over_train_mae'] - 1),
            game, u['train_mae'], u['test_mae'],
            100 * (u['test_over_train_mae'] - 1)))
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    return '\n'.join(lines)


def main():
    rows = load()
    for name, text in (('table.tex', latex(rows)),
                       ('table_wide.tex', latex_wide(rows))):
        path = os.path.join(HERE, name)
        with open(path, 'w') as fh:
            fh.write(text)
        print('wrote %s' % path)
    print()
    print(markdown(rows))


if __name__ == '__main__':
    main()
