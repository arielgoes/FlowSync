"""
Script: train_ipi_model.py
Overview:
    This script trains a GRU-based model to predict Inter-Packet Intervals (IPI).
    It processes the input CSV (generated by extract_traffic_csv.py), performs
    preprocessing (scaling, outlier removal), splits the data, and trains the model.
    It saves the trained model (.keras), scalers (.joblib), and dataset splits (.npz, .csv).

Usage:
    python3 train_ipi_model.py --input_file <path> --output_prefix <prefix> --direction <DL|UL> --n_packets <N>

Example:
    python3 train_ipi_model.py \
      --input_file Forza_DL.csv \
      --output_prefix Forza \
      --direction DL \
      --n_packets 10000
"""
import sys
import os
import argparse
import pandas as pd
import numpy as np
import tensorflow as tf
from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, GRU, Dense, Conv1D, MaxPooling1D, Attention, Flatten, LSTM, MultiHeadAttention, BatchNormalization, LayerNormalization, Dropout
from tensorflow.keras.callbacks import ModelCheckpoint
from tensorflow.keras.optimizers import Adam, Nadam, RMSprop, AdamW
from tensorflow.keras import backend as K
from tensorflow.keras import regularizers
from tensorflow.keras.initializers import GlorotUniform, HeNormal, Orthogonal
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
import joblib

def parse_args():
    parser = argparse.ArgumentParser(description="Train IPI prediction model.")
    parser.add_argument("--input_file", type=str, required=True, help="Path to the input CSV file.")
    parser.add_argument("--output_prefix", type=str, default="model", help="Prefix for output files (model, scaler).")
    parser.add_argument("--direction", type=str, choices=["DL", "UL"], required=True, help="Traffic direction (DL or UL).")
    parser.add_argument("--epochs", type=int, default=50, help="Number of training epochs.")
    parser.add_argument("--window_size", type=int, default=10, help="Window size.")
    parser.add_argument("--n_packets", type=int, default=10000, help="Number of first packets to use.")
    return parser.parse_args()

def remove_outliers(df, columns):
    for col in columns:
        lower_bound = np.percentile(df[col], 0.1)  # 1st percentile
        upper_bound = np.percentile(df[col], 99.9)  # 99th percentile
        df = df[(df[col] >= lower_bound) & (df[col] <= upper_bound)]  # Filter rows within bounds
    return df

def create_complete_windows(group, window_size, target=[], ignored_features=[]):
    """Helper function to create complete windows from a group, excluding specified features from sequences."""
    sequences, targets = [], []
    num_windows = (len(group) - window_size) // window_size  # Count of complete windows

    # Determine feature columns to use for input sequences
    feature_columns = group.columns.difference(ignored_features)

    if num_windows > 0:
        for i in range(num_windows):
            start_idx = i * window_size
            end_idx = start_idx + window_size

            # Append the features (excluding target and ignored features) to sequences
            sequences.append(group.iloc[start_idx:end_idx][feature_columns].to_numpy())

            # Append the target value at 'end_idx' to the targets list
            targets.append(group.iloc[end_idx][target].to_numpy() if len(target) > 1 else group.iloc[end_idx][target])
    
    return sequences, targets

def mish(x):
    return x * K.tanh(K.softplus(x))

def create_model10_temp(output_size=1, window_size=10, num_features=1, num_rnn_neurons=[128, 64], 
                        filter_sizes=[64, 32], print_summary=False, 
                        loss_func=['mae'], learning_rate=0.001, dropout_rnn=0.25, dropout_window=0,
                        activation_rnn='relu', activation_conv='relu', 
                        activation_dense='tanh', activation_out=None, 
                        l1_reg=0, l2_reg=0.001, conv_kernels=[5, 3], num_dense_neurons=[64, 32], optimizer='Adam',
                        use_layer_norm=False, use_lstm=False, use_attention=True, num_attention_heads=2, stateful=False):
    
    # Define the input layer
    inputs = Input(shape=(window_size, num_features))

    # Add Conv1D and MaxPooling1D layers if conv_kernels list is provided
    x = inputs
    if conv_kernels:
        for i, (kernel_size, num_filters) in enumerate(zip(conv_kernels, filter_sizes)):
            if activation_conv == 'relu':
                x = Conv1D(filters=num_filters, kernel_size=kernel_size, padding='same', 
                           activation=activation_conv, kernel_initializer=HeNormal())(x)
            elif activation_conv == 'tanh':
                x = Conv1D(filters=num_filters, kernel_size=kernel_size, padding='same', 
                           activation=activation_conv, kernel_initializer=GlorotUniform())(x)
            else:
                x = Conv1D(filters=num_filters, kernel_size=kernel_size, padding='same', 
                           activation=activation_conv)(x)
            x = BatchNormalization()(x)  # Add batch normalization
            x = MaxPooling1D(pool_size=2)(x)  # Reduce sequence length by half
    else:
        x = inputs  # Skip convolution if add_conv_layers is False

    # Choose between GRU and LSTM based on the use_lstm flag
    rnn_layer = LSTM if use_lstm else GRU

    # Add RNN layers (GRU or LSTM), progressively reducing neuron counts if specified
    for i, neurons in enumerate(num_rnn_neurons[:len(num_rnn_neurons)]):
        return_seq = True if (i < len(num_rnn_neurons) - 1 or use_attention) else False
        if activation_rnn == 'relu':
            # Note: mish is handled if passed as object, but here we expect string 'relu' or 'tanh' usually, 
            # or the object itself. If string, standard keras activations.
            x = rnn_layer(neurons, activation=activation_rnn, return_sequences=return_seq,  
                        dropout=dropout_rnn if dropout_rnn > 0 else 0, recurrent_dropout=dropout_window if dropout_window > 0 else 0,
                        kernel_regularizer=regularizers.L1L2(l1=l1_reg, l2=l2_reg) if l1_reg > 0 or l2_reg > 0 else None,
                        kernel_initializer=HeNormal(), stateful=stateful)(x)
        elif activation_rnn == 'tanh':
            x = rnn_layer(neurons, activation=activation_rnn, return_sequences=return_seq,  
                        dropout=dropout_rnn if dropout_rnn > 0 else 0, recurrent_dropout=dropout_window if dropout_window > 0 else 0,
                        kernel_regularizer=regularizers.L1L2(l1=l1_reg, l2=l2_reg) if l1_reg > 0 or l2_reg > 0 else None,
                        kernel_initializer=GlorotUniform(), stateful=stateful)(x)
        else:
            x = rnn_layer(neurons, activation=activation_rnn, return_sequences=return_seq,  
                        dropout=dropout_rnn if dropout_rnn > 0 else 0, recurrent_dropout=dropout_window if dropout_window > 0 else 0,
                        kernel_regularizer=regularizers.L1L2(l1=l1_reg, l2=l2_reg) if l1_reg > 0 or l2_reg > 0 else None,
                        stateful=stateful)(x)
        
        # Apply Layer Normalization after each RNN layer if enabled
        if use_layer_norm:
            x = LayerNormalization()(x)
    
    if use_attention and num_attention_heads > 0 and num_attention_heads <= 1:
        # Use the last output from the GRU as both the query and value
        attention_output = Attention()([x, x])
        x = Flatten()(attention_output)  # Flatten if you plan to use Dense layer

    elif use_attention and num_attention_heads > 1:
        # Use MultiHeadAttention for attention mechanism
        attention_output = MultiHeadAttention(num_heads=num_attention_heads, 
                                              kernel_initializer=Orthogonal(), key_dim=num_rnn_neurons[-1])(x, x)
        
        # You might want to add a skip connection or layer normalization after attention
        x = x + attention_output  # Skip connection
        x = LayerNormalization()(x)  # Optional: add layer normalization

    x = Flatten()(x)  # Flatten if you plan to use Dense layer

    # Add dense layers specified in num_dense_neurons list
    for neurons in num_dense_neurons:
        x = Dense(neurons, activation=activation_dense, kernel_initializer=GlorotUniform())(x)
        x = BatchNormalization()(x)  # Add batch normalization

    # Final Dense output layer
    if activation_out == None:
        outputs = Dense(output_size, activation=None, kernel_initializer=GlorotUniform())(x)
    else:
        outputs = Dense(output_size, activation=activation_out, kernel_initializer=GlorotUniform())(x)

    # Create the model
    model = Model(inputs=inputs, outputs=outputs)
    
    if print_summary:
        model.summary()

    if optimizer == 'Adam':
        optimizer_obj = Adam(learning_rate=learning_rate, amsgrad=False)
    elif optimizer == 'AMSgrad':
        optimizer_obj = Adam(learning_rate=learning_rate, amsgrad=True)
    elif optimizer == 'Nadam':
        optimizer_obj = Nadam(learning_rate=learning_rate)
    elif optimizer == 'RMSprop':
        optimizer_obj = RMSprop(learning_rate=learning_rate)
    elif optimizer == 'AdamW':
        optimizer_obj = AdamW(learning_rate=learning_rate)
    else:
        optimizer_obj = Adam(learning_rate=learning_rate)

    model.compile(loss=loss_func, 
                optimizer=optimizer_obj, 
                metrics=['mae'])

    return model

def main():
    args = parse_args()

    print(f"Loading file: {args.input_file}")
    df = pd.read_csv(args.input_file, header=0)

    # Preprocessing
    # Multiply IPI by 1e6
    if 'IPI' in df.columns:
        df['IPI'] *= 1e6
    else:
        print("Error: 'IPI' column not found in input file.")
        sys.exit(1)

    # Drop NaN columns
    df = df.dropna(axis=1, how='all')
    if "Unnamed: 0" in df.columns:
        df = df.drop(columns=["Unnamed: 0"])
    
    # Keep only IPI
    df = df[['IPI']]

    # Remove outliers
    columns_to_check = ['IPI']
    df = remove_outliers(df, columns=columns_to_check)

    # Keep only first N packets
    df_remaining = None
    if args.n_packets > 0 and len(df) > args.n_packets:
        print(f"Splitting data: First {args.n_packets} packets for training, rest for 'remaining'.")
        
        # Save remaining packets
        df_remaining = df.iloc[args.n_packets:].copy()
        df = df.iloc[:args.n_packets]
        
        # Scale remaining packets
        scaler_remaining = MinMaxScaler(feature_range=(-1, 1))
        scaled_data_remaining = scaler_remaining.fit_transform(df_remaining)
        df_remaining_scaled = pd.DataFrame(scaled_data_remaining, columns=df_remaining.columns, index=df_remaining.index)
        
        # Save remaining scaler and CSV
        remaining_scaler_filename = f"{args.output_prefix}_{args.direction}_scaler_remaining.joblib"
        joblib.dump(scaler_remaining, remaining_scaler_filename)
        print(f"Saved remaining scaler to {remaining_scaler_filename}")
        
        remaining_csv_filename = f"{args.output_prefix}_{args.direction}_packets_N_to_end_scaled.csv"
        df_remaining_scaled.to_csv(remaining_csv_filename, index=False)
        print(f"Saved remaining scaled packets to {remaining_csv_filename}")
    
    # Split data
    if 'Class' in df.columns:
        df = df.drop('Class', axis=1)

    train_df, test_df = train_test_split(df, test_size=0.2, shuffle=False, random_state=42)

    # Scale data
    scaler = MinMaxScaler(feature_range=(-1, 1))
    train_df = pd.DataFrame(scaler.fit_transform(train_df), columns=df.columns)
    test_df = pd.DataFrame(scaler.transform(test_df), columns=df.columns)

    # Save scaler
    scaler_filename = f"{args.output_prefix}_{args.direction}_scaler.joblib"
    joblib.dump(scaler, scaler_filename)
    print(f"Saved scaler to {scaler_filename}")

    # Create windows
    target_columns = ['IPI']
    X_train, y_train = create_complete_windows(train_df, args.window_size, target=target_columns)
    X_test, y_test = create_complete_windows(test_df, args.window_size, target=target_columns)

    X_train = np.array(X_train)
    y_train = np.array(y_train)
    X_test = np.array(X_test)
    y_test = np.array(y_test)

    # Save train/test splits
    splits_filename = f"{args.output_prefix}_{args.direction}_train_test_splits.npz"
    np.savez_compressed(splits_filename, 
                        X_train=X_train, y_train=y_train, 
                        X_test=X_test, y_test=y_test)
    print(f"Saved train/test splits to {splits_filename}")

    print(f"X_train shape: {X_train.shape}")

    # Create model
    # Using hyperparameters from notebook
    model = create_model10_temp(
        output_size=1,
        window_size=X_train.shape[1],
        num_features=X_train.shape[2],
        num_rnn_neurons=[128, 128],
        print_summary=True,
        dropout_rnn=0.2,
        dropout_window=0.2,
        loss_func=['mae'],
        activation_rnn=mish,
        activation_conv='tanh',
        activation_out='tanh',
        learning_rate=0.0001,
        use_layer_norm=True,
        num_attention_heads=8,
        l1_reg=0.001,
        l2_reg=0.001,
        conv_kernels=[3, 5, 7],
        filter_sizes=[128, 128, 128],
        optimizer='Adam',
        num_dense_neurons=[],
        use_lstm=False,
        use_attention=False,
        activation_dense='tanh',
        stateful=False
    )

    # Train model
    model_filename = f"{args.output_prefix}_{args.direction}.keras"
    cp = ModelCheckpoint(model_filename, monitor='loss', mode='min', save_best_only=True)

    print("Starting training...")
    history = model.fit(X_train, y_train, epochs=args.epochs, batch_size=32, callbacks=[cp])
    print("Training complete.")
    print(f"Model saved to {model_filename}")

if __name__ == "__main__":
    main()
